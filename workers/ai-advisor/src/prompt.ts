import type { ChatMessage } from './providers'

export type AdvisorMode = 'chat' | 'market' | 'radar' | 'coin' | 'trade'

const MAX_HISTORY = 8
const MAX_MESSAGE_CHARS = 2_500
const MAX_SNAPSHOT_CHARS = 40_000

